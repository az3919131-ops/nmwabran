const { launch, fileUrl } = require('./harness.cjs');
const fs = require('fs');
const OUT = process.env.OUT || '/tmp/claude-0/-home-user-nmwabran/bcbad044-f9e9-50f8-94b4-ce0e32325ad5/scratchpad/shots';
fs.mkdirSync(OUT, { recursive: true });
const W = Number(process.env.W || 1440);
const H = Number(process.env.H || 900);

(async () => {
  const { browser, page, errors } = await launch({ width: W, height: H, mobile: W < 700 });
  const over = async (name) => {
    const r = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, iw: window.innerWidth }));
    console.log(name, r.sw > r.iw + 1 ? 'OVERFLOW ' + r.sw + '>' + r.iw : 'ok');
  };
  const shot = async (n, full = true) => { await page.waitForTimeout(350); await page.screenshot({ path: `${OUT}/${W}-${n}.png`, fullPage: full }); await over(n); };
  await page.goto(fileUrl());
  await page.waitForSelector('.login-card');
  await shot('01-login');
  await page.fill('input[name=name]', 'م. أحمد زهران');
  await page.click('button[type=submit]');
  await page.waitForSelector('#add-demo');
  await page.click('#add-demo');
  await page.waitForSelector('.kpis');
  await shot('02-dashboard');
  await page.goto(fileUrl('#/compare'));
  await page.waitForSelector('.table');
  await shot('03-compare');
  await page.goto(fileUrl('#/compare?status=none'));
  await page.waitForSelector('.table');
  await shot('04-compare-none');
  await page.click('[data-detail]');
  await page.waitForSelector('dialog[open]');
  await shot('05-detail', false);
  await page.keyboard.press('Escape');
  await page.goto(fileUrl('#/compare?view=orders'));
  await page.waitForSelector('.wo-card');
  await shot('06-orders');
  await page.goto(fileUrl('#/reports?tab=shortage'));
  await page.waitForSelector('.table');
  await shot('07-report-shortage');
  await page.goto(fileUrl('#/import/checklist'));
  await page.waitForSelector('.dropzone');
  await shot('08-import');
  await page.goto(fileUrl('#/catalog'));
  await page.waitForSelector('.table');
  await shot('09-catalog');
  await page.goto(fileUrl('#/projects'));
  await page.waitForSelector('.project-card');
  await shot('10-projects');
  console.log('ERRORS', errors);
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
